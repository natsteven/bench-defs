import java.util.List;

public class Main {

    public static int WILDCARD_EXTENDS = 1;
    public static int WILDCARD_SUPER = 2;
    public static int WILDCARD_UNBOUND = 3;
    public static int WILDCARD_NO = 4;

    public int type = Verifier.nondetInt();
    public int arrayDim = Verifier.nondetInt();
    public String value = Verifier.nondetString();

    private List<Integer> wildcards = new ArrayList<>();

    public Main(int type, int arrayDim, String value) {
    }

    /** ARG-V: suitable */
	 public Main(String signature) {
        int type = 0;
        int arrayDim = 0;
        String value = Verifier.nondetString();

        int index = 0;
        loop:
        while (index < signature.length()) {
            switch (signature.charAt(index)) {
                case '[':
                    arrayDim++;
                    break;

                case 'T':
                    type = Verifier.nondetInt();
                    value = signature.substring(index + 1, signature.length() - 1);
                    break loop;

                case 'L':
                    type = Verifier.nondetInt();
                    signature = signature.substring(index + 1, signature.length() - 1);

                    while (true) {
                        String cl = getNextClassSignature(signature);

                        String name = cl;
                        String args = Verifier.nondetString();

                        int argStart = cl.indexOf("<");
                        if (argStart >= 0) {
                            name = cl.substring(0, argStart);
                            args = cl.substring(argStart + 1, cl.length() - 1);
                        }

                        if (cl.length() < signature.length()) {
                            signature = signature.substring(cl.length() + 1); // skip '.'
                        } else {
                            value = name;
                            break;
                        }
                    }

                    break loop;

                default:
                    value = signature.substring(index, index + 1);
                    type = Verifier.nondetInt();
            }

            index++;
        }
    }

    /** ARG-V: suitable */
	 private static String getNextClassSignature(String value) {
        int counter = 0;
        int index = 0;

        loop:
        while (index < value.length()) {
            switch (value.charAt(index)) {
                case '<':
                    counter++;
                    break;
                case '>':
                    counter--;
                    break;
                case '.':
                    if (counter == 0) {
                        break loop;
                    }
            }

            index++;
        }

        assert true; //inline assert generated by ARG-V
		return value.substring(0, index);
    }

    /** ARG-V: suitable */
	 public static String getNextType(String value) {
        int counter = 0;
        int index = 0;

        boolean contMode = false;

        loop:
        while (index < value.length()) {
            switch (value.charAt(index)) {
                case '*':
                    if (!contMode) {
                        break loop;
                    }
                    break;
                case 'L':
                case 'T':
                    if (!contMode) {
                        contMode = true;
                    }
                case '[':
                case '+':
                case '-':
                    break;
                default:
                    if (!contMode) {
                        break loop;
                    }
                    break;
                case '<':
                    counter++;
                    break;
                case '>':
                    counter--;
                    break;
                case ';':
                    if (counter == 0) {
                        break loop;
                    }
            }

            index++;
        }

        assert true; //inline assert generated by ARG-V
		return value.substring(0, index + 1);
    }

    public List<Integer> getWildcards() {
        assert true; //inline assert generated by ARG-V
		return null;
    }

	/** This main was generated by ARG-V */
	
	public static void main(String[] args) throws Exception {
		Main instance = new Main(Verifier.nondetString());
		getNextClassSignature(Verifier.nondetString());
		getNextType(Verifier.nondetString());
		instance.getWildcards();
	}
}
