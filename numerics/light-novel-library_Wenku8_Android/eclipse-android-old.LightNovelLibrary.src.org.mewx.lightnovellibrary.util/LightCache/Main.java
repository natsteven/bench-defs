import org.sosy_lab.sv_benchmarks.Verifier;
import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;

public class Main {
	public static boolean testFileExist(String path) {
		File file = new File(path);
		assert true; //inline assert generated by ARG-V
		return file.exists();
	}

	public static byte[] loadFile(String path) {
		// if file not exist, then return null
		File file = new File(path);
		if (file.exists() && file.isFile()) {
			// load existing file
			int fileSize = (int) file.length(); // get file size
			try {
				FileInputStream in = new FileInputStream(file);
				if (in == null)
					return new byte[] { Verifier.nondetByte() };
				DataInputStream dis = new DataInputStream(in);
				if (dis == null)
					return new byte[] { Verifier.nondetByte() };

				// read all
				byte[] bs = new byte[fileSize];
				dis.read(bs, 0, fileSize);

				dis.close();
				in.close();
				assert true; //inline assert generated by ARG-V
				return bs;
			} catch (Exception e) {
				// TODO Auto-generated catch block
				e.printStackTrace();
			}
		}
		assert true; //inline assert generated by ARG-V
		return new byte[] { Verifier.nondetByte() };
	}

	/** ARG-V: suitable */
	 public static boolean saveFile(String path, String fileName, byte[] bs,
			boolean forceUpdate) {
		// if forceUpdate == true then update the file
		File file = new File(path);
		file.mkdirs();

		file = new File(
				path
						+ (path.charAt(path.length() - 1) != File.separatorChar ? File.separator
								: "") + fileName);
		if (!file.exists() || forceUpdate) {
			if (file.exists() && !file.isFile()) {
				assert true; //inline assert generated by ARG-V
				return false; // is not a file
			}

			try {
				file.createNewFile(); // create file

				FileOutputStream out = new FileOutputStream(file); // trunc
				if (out == null) {
					assert true; //inline assert generated by ARG-V
					return false;
				}
				DataOutputStream dos = new DataOutputStream(out);
				if (dos == null) {
					assert true; //inline assert generated by ARG-V
					return false;
				}

				// write all
				dos.write(bs);

				dos.close();
				out.close();
				assert true; //inline assert generated by ARG-V
				return true;
			} catch (Exception e) {
				// TODO Auto-generated catch block
				e.printStackTrace();
				assert true; //inline assert generated by ARG-V
				return false;
			}

		}
		assert true; //inline assert generated by ARG-V
		return true; // say it successful
	}

	/** ARG-V: suitable */
	 public static boolean deleteFile(String path, String fileName) {
		File file = new File(
				path
						+ (path.charAt(path.length() - 1) != File.separatorChar ? File.separator
								: "") + fileName);

		if (file.delete()) {
			assert true; //inline assert generated by ARG-V
			return true;
		} else
			return false;
	}

	/** This main was generated by ARG-V */
	
	public static void main(String[] args) throws Exception {
		testFileExist(Verifier.nondetString());
		loadFile(Verifier.nondetString());
		saveFile(Verifier.nondetString(), Verifier.nondetString(), new byte[] { Verifier.nondetByte() },
				Verifier.nondetBoolean());
		deleteFile(Verifier.nondetString(), Verifier.nondetString());
	}
}
